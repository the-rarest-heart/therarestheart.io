#!/bin/bash
# =============================================================
# TRH Context Updater
# Run this from inside your project folder:
#   bash update-context.sh
#
# What it does:
#   1. Scans your actual folder structure
#   2. Lists real files that exist
#   3. Rewrites the [ACTUAL FILES] section of your CLAUDE.md
#   4. Updates trh-context.md with real SOPs, lessons, and pages
# =============================================================

PROJECT_DIR="$(pwd)"
PROJECT_NAME="$(basename "$PROJECT_DIR")"
CLAUDE_FILE="$PROJECT_DIR/CLAUDE.md"
CONTEXT_FILE="$PROJECT_DIR/trh-context.md"
TIMESTAMP=$(date +"%B %Y")

echo ""
echo "=============================="
echo " TRH Context Updater"
echo " Project: $PROJECT_NAME"
echo " Location: $PROJECT_DIR"
echo "=============================="
echo ""

# ── STEP 1: Scan real folder structure ──────────────────────
echo "► Scanning folder structure..."

TREE_OUTPUT=$(find . \
  -not -path '*/.git/*' \
  -not -path '*/node_modules/*' \
  -not -path '*/__pycache__/*' \
  -not -path '*/.DS_Store' \
  -not -name '*.pyc' \
  -not -name '.gitignore' \
  | sort | sed 's|./||' | head -80)

echo "$TREE_OUTPUT"
echo ""

# ── STEP 2: Detect project type ─────────────────────────────
IS_WEBSITE=false
IS_GERD=false

if [ -f "index.html" ] || [ -f "learn.html" ]; then
  IS_WEBSITE=true
  echo "► Detected: Website project (therarestheart.io)"
fi

if [ -f "CLAUDE.md" ] && grep -q "TheGERD\|ollama\|Ollama" CLAUDE.md 2>/dev/null; then
  IS_GERD=true
  echo "► Detected: TheGERD project"
fi

if [ -d "knowledge" ] || [ -d "agents" ] || [ -d "workflows" ]; then
  IS_GERD=true
  echo "► Detected: TheGERD project (folder structure)"
fi

echo ""

# ── STEP 3: Collect real files by type ──────────────────────

# HTML pages that actually exist
HTML_PAGES=$(find . -maxdepth 2 -name "*.html" | sort | sed 's|./||')

# SOPs that actually exist
SOPS=$(find . -path "*/sops/*.md" -o -path "*/sop*.md" 2>/dev/null | sort | sed 's|./||')

# Lesson JSON files
LESSONS=$(find . -name "*.json" -path "*/lesson*" 2>/dev/null | sort | sed 's|./||')

# n8n workflow files
WORKFLOWS=$(find . -name "*.json" -path "*/workflow*" 2>/dev/null | sort | sed 's|./||')

# Agent prompt files
AGENTS=$(find . -path "*/agents/*.md" 2>/dev/null | sort | sed 's|./||')

# Scripts
SCRIPTS=$(find . -name "*.sh" 2>/dev/null | sort | sed 's|./||')

# Images/assets
IMAGES=$(find . -path "*/images/*" -o -path "*/assets/*" 2>/dev/null | head -20 | sort | sed 's|./||')

# ── STEP 4: Build the ACTUAL FILES section ───────────────────
echo "► Building actual file inventory..."

ACTUAL_FILES_SECTION="## ACTUAL FILES (Auto-generated — do not edit manually)
> Last scanned: $TIMESTAMP by update-context.sh

### Full Folder Structure
\`\`\`
$TREE_OUTPUT
\`\`\`
"

if [ -n "$HTML_PAGES" ]; then
ACTUAL_FILES_SECTION="$ACTUAL_FILES_SECTION
### HTML Pages That Exist
\`\`\`
$HTML_PAGES
\`\`\`
"
fi

if [ -n "$SOPS" ]; then
ACTUAL_FILES_SECTION="$ACTUAL_FILES_SECTION
### SOPs in Knowledge Base
\`\`\`
$SOPS
\`\`\`
"
fi

if [ -n "$AGENTS" ]; then
ACTUAL_FILES_SECTION="$ACTUAL_FILES_SECTION
### Agent Prompt Files
\`\`\`
$AGENTS
\`\`\`
"
fi

if [ -n "$WORKFLOWS" ]; then
ACTUAL_FILES_SECTION="$ACTUAL_FILES_SECTION
### n8n Workflows
\`\`\`
$WORKFLOWS
\`\`\`
"
fi

if [ -n "$SCRIPTS" ]; then
ACTUAL_FILES_SECTION="$ACTUAL_FILES_SECTION
### Scripts
\`\`\`
$SCRIPTS
\`\`\`
"
fi

# ── STEP 5: Write/update CLAUDE.md ──────────────────────────
if [ -f "$CLAUDE_FILE" ]; then
  echo "► Updating existing CLAUDE.md..."

  # Remove old auto-generated section if it exists
  # Then append the new one
  if grep -q "ACTUAL FILES (Auto-generated" "$CLAUDE_FILE"; then
    # Remove from the auto-generated marker to end of file
    sed -i.bak '/^## ACTUAL FILES (Auto-generated/,$ d' "$CLAUDE_FILE"
    echo "" >> "$CLAUDE_FILE"
  fi

  # Append the new actual files section
  echo "$ACTUAL_FILES_SECTION" >> "$CLAUDE_FILE"
  echo "  ✓ CLAUDE.md updated"

else
  echo "► No CLAUDE.md found — creating minimal one..."
  cat > "$CLAUDE_FILE" << EOF
# CLAUDE.md — $PROJECT_NAME
> Auto-generated by update-context.sh
> Add your project description above this line.

$ACTUAL_FILES_SECTION
EOF
  echo "  ✓ CLAUDE.md created"
fi

# ── STEP 6: Update trh-context.md module/page status ────────
if [ -f "$CONTEXT_FILE" ]; then
  echo ""
  echo "► Checking trh-context.md for pages to update..."

  # Check which pages exist and note them
  if [ "$IS_WEBSITE" = true ]; then
    echo ""
    echo "  Page status (based on real files):"
    for page in index.html learn.html do.html apply.html topics.html assistant.html contact.html; do
      if [ -f "$page" ]; then
        echo "  ✓ $page — EXISTS"
      else
        echo "  ✗ $page — NOT YET BUILT"
      fi
    done
  fi

  if [ "$IS_GERD" = true ]; then
    echo ""
    echo "  Agent status (based on real files):"
    for agent in content-agent sop-agent client-agent educator-agent; do
      if [ -f "agents/$agent.md" ]; then
        echo "  ✓ agents/$agent.md — EXISTS"
      else
        echo "  ✗ agents/$agent.md — NOT YET BUILT"
      fi
    done

    echo ""
    echo "  Knowledge base:"
    SOP_COUNT=$(find . -path "*/sops/*.md" 2>/dev/null | wc -l | tr -d ' ')
    LESSON_COUNT=$(find . -path "*/lessons/*.json" 2>/dev/null | wc -l | tr -d ' ')
    echo "  SOPs indexed: $SOP_COUNT"
    echo "  Lessons indexed: $LESSON_COUNT"
  fi
fi

# ── STEP 7: Print summary for Claude Code ───────────────────
echo ""
echo "=============================="
echo " Summary for Claude Code"
echo "=============================="
echo ""
echo "Project: $PROJECT_NAME"
echo "Location: $PROJECT_DIR"
echo "Scanned: $TIMESTAMP"
echo ""
echo "When you open this project in Claude Code, it will now"
echo "automatically read your real folder structure from CLAUDE.md"
echo ""
echo "To keep it current, run:"
echo "  bash update-context.sh"
echo ""
echo "To tell Claude Code about a specific file, type:"
echo "  @filename.html or @foldername/file.md"
echo ""
echo "=============================="
